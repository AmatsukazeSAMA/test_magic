def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def evidence(p):
    p = Path(p)
    return {'path': str(p), 'sha256': sha(p)}
def save_new(name, obj):
    p = RUN / name
    if p.exists():
        raise FileExistsError(p)
    p.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return evidence(p)

